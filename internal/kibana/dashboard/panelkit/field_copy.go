package panelkit

import (
	"github.com/elastic/terraform-provider-elasticstack/internal/utils/typeutils"
	"github.com/hashicorp/terraform-plugin-framework/types"
)

// CopyKnownString returns a pointer to v's value when v is known (non-null, non-unknown);
// otherwise nil. Replaces the repeated "if typeutils.IsKnown(x) { dst = x.ValueStringPointer() }"
// block used when copying optional TF model fields into generated by_field/by_esql API structs.
func CopyKnownString(v types.String) *string {
	if typeutils.IsKnown(v) {
		return v.ValueStringPointer()
	}
	return nil
}

// CopyKnownBool is the bool equivalent of CopyKnownString.
func CopyKnownBool(v types.Bool) *bool {
	if typeutils.IsKnown(v) {
		return v.ValueBoolPointer()
	}
	return nil
}

// CopyKnownFloat32 is the float32 equivalent of CopyKnownString.
func CopyKnownFloat32(v types.Float32) *float32 {
	if typeutils.IsKnown(v) {
		return v.ValueFloat32Pointer()
	}
	return nil
}

// CommonControlFields holds the by_field/by_esql control attributes shared across dashboard panel
// control types (e.g. options list, range slider): a title override, whether the control respects
// dashboard-level global filters, and whether it should ignore validations.
type CommonControlFields struct {
	Title             types.String
	UseGlobalFilters  types.Bool
	IgnoreValidations types.Bool
}

// CommonControlFieldsAPI mirrors CommonControlFields as the optional pointer fields expected by the
// generated by_field/by_esql API request structs.
type CommonControlFieldsAPI struct {
	Title             *string
	UseGlobalFilters  *bool
	IgnoreValidations *bool
}

// BuildCommonControlFields converts the shared TF model attributes into their API pointer form,
// replacing the identical copy-if-known block previously duplicated across every by_field/by_esql
// config builder.
func BuildCommonControlFields(cfg CommonControlFields) CommonControlFieldsAPI {
	return CommonControlFieldsAPI{
		Title:             CopyKnownString(cfg.Title),
		UseGlobalFilters:  CopyKnownBool(cfg.UseGlobalFilters),
		IgnoreValidations: CopyKnownBool(cfg.IgnoreValidations),
	}
}
